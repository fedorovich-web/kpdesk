def build_taxonomy_coverage() -> dict[str, Any]:
    document = build_natural_category_curriculum()
    catalog: list[dict[str, Any]] = document["catalog"]
    queries: list[dict[str, Any]] = document["queries"]
    covered = {item["category"] for item in catalog}
    missing = CATEGORY_ATTRIBUTES.keys() - covered
    if set(_EXAMPLES) != missing or set(_ATTRIBUTES) != missing:
        raise ValueError("Synthetic category expansion must cover precisely missing taxonomy classes.")
    seen = {normalize_text(item["request"]["description"]) for item in queries}
    if len(seen) != len(queries):
        raise ValueError("Source category corpus contains duplicate query text.")
    for category, variants in sorted(_EXAMPLES.items()):
        if len(variants) < 5 or not REQUIRED_PRODUCT_ATTRIBUTES[category] <= _ATTRIBUTES[category].keys():
            raise ValueError(f"Insufficient independent product coverage: {category}")
        for index, (name, paraphrase) in enumerate(variants, start=1):
            sku = f"a46-{category}-{index}"
            product = CatalogProduct.model_validate({
                "sku": sku, "name": name, "category": category,
                "sale_unit": "штука", "pieces_per_sale_unit": 1,
                "price_rub": "100.00", "attributes": _ATTRIBUTES[category],
            })
            catalog.append(product.model_dump(mode="json"))
            for wording, phrase in enumerate((name, paraphrase), start=1):
                normalized = normalize_text(phrase)
                if normalized in seen:
                    raise ValueError(f"Duplicated category wording: {category}")
                seen.add(normalized)
                request = RequestedItem.model_validate({
                    "category": category, "description": phrase,
                    "quantity": 1, "unit": "штука",
                })
                queries.append({
                    "query_id": f"{sku}-{wording}",
                    "query_group_id": f"intent-{sku}",
                    "request": request.model_dump(mode="json"),
                    "relevant_skus": [sku],
                })
    document["provenance"] = {
        "kind": "synthetic_example",
        "annotation_method": "hand_authored_taxonomy_v4_category_intents_a46",
        "synthetic_only": True,
        "independent_gold": False,
        "source_customer_gold": False,
        "production_training": False,
        "external_holdout_used_for_training": False,
    }
    return document


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args(argv)
    if args.output.exists():
        raise FileExistsError("Refusing to overwrite synthetic taxonomy corpus.")
    data = build_taxonomy_coverage()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    with args.output.open("x", encoding="utf-8") as destination:
        json.dump(data, destination, ensure_ascii=False, sort_keys=True, indent=2)
        destination.write("\n")
    loaded = load_dataset(args.output)
    split = stratified_category_groups(loaded.queries)
    print(json.dumps({
        "categories": len({row.request.category for row in loaded.queries}),
        "catalog": len(loaded.products),
        "queries": len(loaded.queries),
        "groups": len({row.query_group_id for row in loaded.queries}),
        "train": len(split.train), "validation": len(split.validation),
        "test": len(split.test), "sha256": loaded.source_sha256,
    }, ensure_ascii=False, sort_keys=True))
    return 0


