"""One commercial-copy policy for both author and factual reviewer."""

def has_company_facts(data: object) -> bool:
    """Presence only; the semantic reviewer still checks what the facts support."""
    company = data.get('company_facts') if isinstance(data, dict) else None
    return isinstance(company, dict) and any(
        isinstance(company.get(key), str) and company[key].strip()
        for key in ('about', 'advantages')
    )


